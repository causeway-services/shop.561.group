import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { resolve, dirname } from "node:path";

const expectedSource = "https://market.561.group/v1/catalog";
const expectedSourceId = "house-x402";
const offerPrefix = "https://bazaar.561.group/offers?source=house-x402&id=";
const generatedHeader = "// Generated by scripts/compile-catalog.mjs from catalog.json and each book's records. Do not edit.\n";

const record = value => value !== null && typeof value === "object" && !Array.isArray(value);
const same = (a, b) => JSON.stringify(a) === JSON.stringify(b);
function requireThat(ok, message) {
  if (!ok) throw new TypeError(message);
}

/**
 * Reproject ONLY the seller-authored agentOfferUrl fields over a previously
 * received edition compilation. This never compiles manuscripts or attests to
 * present availability, signed payments, or new edition acceptance.
 *
 * The normal compile-catalog.mjs remains authoritative for every content,
 * edition, print, cover, payment, merchant and rights change.
 */
export function reconcileAuthoredOfferLinks(authored, previous, evidence) {
  requireThat(record(authored) && record(previous) && record(evidence), "Original sources must be records");
  requireThat(Array.isArray(authored.offerings) && Array.isArray(previous.offerings) &&
    authored.offerings.length === previous.offerings.length, "Original seller catalog inventory diverged");
  requireThat(same(authored.merchant, previous.merchant), "Original merchant authority changed");
  requireThat(same(authored.externalStripePaymentLinkReceivers, previous.externalStripePaymentLinkReceivers),
    "External merchant receiving declarations changed");
  requireThat(evidence.source === expectedSource && evidence.sourceId === expectedSourceId &&
    Array.isArray(evidence.offers), "Original Bazaar publication identity source is not admitted");

  const identities = new Map();
  for (const entry of evidence.offers) {
    requireThat(record(entry) && typeof entry.operation === "string" &&
      typeof entry.sku === "string" &&
      /^ni:\/\/\/sha-256;[A-Za-z0-9_-]{43}$/.test(entry.sku) &&
      entry.gateway === "publications" && entry.method === "GET" && entry.listed === true &&
      entry.url === "https://market.561.group/v1/publications/" + encodeURIComponent(entry.operation) &&
      !identities.has(entry.operation), "Unqualified original Bazaar publication identity");
    identities.set(entry.operation, entry.sku);
  }
  requireThat(identities.size === evidence.offers.length, "Duplicate original seller identity");
  const seen = new Set(), updated = [];
  const offerings = authored.offerings.map((row, index) => {
    const previousRow = previous.offerings[index];
    requireThat(record(row) && record(previousRow) && typeof row.id === "string" &&
      !seen.has(row.id) && row.id === previousRow.id, "Unexpected original offering identity or order");
    seen.add(row.id);
    for (const key of Object.keys(row)) {
      if (key === "book" || key === "agentOfferUrl") continue;
      requireThat(same(row[key], previousRow[key]), "Source-owned offering changed outside URL projection: " + row.id + "." + key);
    }
    requireThat((row.book?.manuscript ?? null) === (previousRow.book?.manuscript ?? null) &&
      (row.book?.acceptance ?? null) === (previousRow.book?.edition?.record ?? null) &&
      (row.book?.printAcceptance ?? null) === (previousRow.book?.printEdition?.record ?? null),
      "Original book manuscript or acceptance source changed: " + row.id);
    requireThat(typeof row.status === "string" &&
      (row.status === "live" || row.status === "coming-soon"), "Unadmitted publication status");
    if (Object.hasOwn(row, "agentOfferUrl")) {
      requireThat(row.status === "live" && identities.has(row.id), "Unqualified original seller publication");
      const candidate = offerPrefix + encodeURIComponent(identities.get(row.id));
      requireThat(row.agentOfferUrl === candidate, "Wrong seller, NI, or unexpected Bazaar offer URL");
      const prior = previousRow.agentOfferUrl;
      requireThat(prior === candidate ||
        prior === "https://market.561.group/?q=" + encodeURIComponent(row.id),
        "Unexpected prior link; explicit edition compilation receiving required");
      if (prior !== candidate) updated.push(row.id);
      return {...previousRow, agentOfferUrl: candidate};
    }
    requireThat(!Object.hasOwn(previousRow, "agentOfferUrl"), "Previously compiled unauthorized agent offer");
    return previousRow;
  });
  requireThat(seen.size === authored.offerings.length &&
    [...identities.keys()].every(id => seen.has(id)), "Original Bazaar offer coverage incomplete");
  const catalog = {...previous, offerings};
  // Changes must be limited to this single original author-owned field.
  for (let i = 0; i < previous.offerings.length; i++) {
    const before = {...previous.offerings[i]}, after = {...catalog.offerings[i]};
    delete before.agentOfferUrl; delete after.agentOfferUrl;
    requireThat(same(before, after), "Edition evidence, cost, or fulfillment unexpectedly changed");
  }
  return {catalog, updated};
}

export function generatedModule(catalog) {
  return generatedHeader + "export default " + JSON.stringify(catalog, null, 2) + ";\n";
}

if (import.meta.main) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
  const readJson = path => JSON.parse(readFileSync(resolve(root, path), "utf8"));
  const compiled = await import("../src/compiled-catalog.mjs");
  const {catalog, updated} = reconcileAuthoredOfferLinks(
    readJson("catalog.json"), compiled.default,
    readJson("data/records/commerce-navigation/2026-10-20-original-publication-identities.json")
  );
  const path = resolve(root, "src/compiled-catalog.mjs");
  const generated = generatedModule(catalog);
  const mode = process.argv[2] ?? "--check";
  if (mode === "--check") {
    if (readFileSync(path, "utf8") !== generated) {
      console.error("Author-owned Shop links have not been regenerated: " + updated.join(", "));
      process.exitCode = 1;
    } else {
      console.log("Authored link projection received; edition and payment evidence left unchanged.");
    }
  } else if (mode === "--write") {
    writeFileSync(path, generated);
    console.log(JSON.stringify({updated, changed: updated.length}));
  } else {
    console.error("usage: reconcile-authored-offer-links [--check|--write]");
    process.exitCode = 2;
  }
}
